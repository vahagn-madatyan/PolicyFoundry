"""Config template and source annotation utilities.

Provides CONFIG_TEMPLATE for ``policyfoundry init`` and source annotation
utilities for ``policyfoundry config show``.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import TYPE_CHECKING, Any, cast

import yaml

if TYPE_CHECKING:
    from pathlib import Path

from policyfoundry.config.models import PolicyFoundryConfig


class ConfigSource(Enum):
    """Identifies where a config value originated."""

    DEFAULT = "default"
    GLOBAL_YAML = "~/.policyfoundry/config.yaml"
    LOCAL_YAML = ".policyfoundry.yaml"
    ENV_VAR = "env"
    CLI_FLAG = "--config"


@dataclass
class AnnotatedValue:
    """A config value annotated with its source."""

    value: object
    source: ConfigSource
    key: str


