def _flatten_config(config: PolicyFoundryConfig) -> dict[str, object]:
    """Flatten a config into dotted-key -> value pairs."""
    result: dict[str, object] = {}
    data = config.model_dump()
    for section, values in data.items():
        if isinstance(values, dict):
            for key in cast("dict[str, object]", values):
                result[f"{section}.{key}"] = values[key]
        else:
            result[section] = values
    return result


def _load_yaml_flat(yaml_path: Path) -> dict[str, object]:
    """Load a YAML file and return flattened dotted-key dict."""
    if not yaml_path.exists():
        return {}
    with yaml_path.open() as f:
        data = yaml.safe_load(f)

    if not isinstance(data, dict):
        return {}

    typed_data = cast("dict[str, object]", data)
    result: dict[str, object] = {}
    for section, values in typed_data.items():
        if isinstance(values, dict):
            section_vals = cast(
                "dict[str, object]", values
            )
            for key, val in section_vals.items():
                result[f"{section}.{key}"] = val
        else:
            result[section] = values
    return result


def resolve_with_annotations(
    config: PolicyFoundryConfig,
    global_yaml_path: Path | None = None,
    local_yaml_path: Path | None = None,
) -> dict[str, AnnotatedValue]:
    """Resolve config and annotate each value with its source.

    Determines which source provided each config value by comparing
    against YAML files and defaults.
    """
    flat = _flatten_config(config)

    global_vals: dict[str, object] = {}
    if global_yaml_path is not None:
        global_vals = _load_yaml_flat(global_yaml_path)

    local_vals: dict[str, object] = {}
    if local_yaml_path is not None:
        local_vals = _load_yaml_flat(local_yaml_path)

    default_flat = _flatten_config(PolicyFoundryConfig())

    annotations: dict[str, AnnotatedValue] = {}
    for key, value in flat.items():
        if key in local_vals and value == local_vals[key]:
            if value != default_flat.get(key) or key in local_vals:
                source = ConfigSource.LOCAL_YAML
            else:
                source = ConfigSource.DEFAULT
        elif key in global_vals and value == global_vals[key]:
            source = ConfigSource.GLOBAL_YAML
        elif value != default_flat.get(key):
            source = ConfigSource.ENV_VAR
        else:
            source = ConfigSource.DEFAULT

        annotations[key] = AnnotatedValue(
            value=value, source=source, key=key
        )

    return annotations
